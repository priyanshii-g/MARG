package in.marg.eia;

import static in.marg.eia.EnvironmentalReportModels.*;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.springframework.stereotype.Component;

/** Validates claim provenance and typed numeric support before any report file is written. */
@Component
public class EnvironmentalReportValidator {

    // The dot exclusion prevents chemical notation such as PM2.5 from being
    // interpreted as a free-standing numeric assessment result.
    private static final Pattern NUMBERS = Pattern.compile("(?<![\\p{L}\\p{N}_:.])[-+]?\\d[\\d,]*(?:\\.\\d+)?");
    // Evidence IDs must be stable identifiers containing 2–150 letters, numbers, dot, underscore, colon or hyphen.
    private static final Pattern STABLE_ID = Pattern.compile("[A-Za-z0-9][A-Za-z0-9._:-]{1,149}");
    private static final Set<String> SYSTEM_TOKENS = Set.of(
            "{{project_name}}", "{{project_proponent}}", "{{route_alternative_name}}", "{{study_area}}",
            "{{report_version}}", "{{assessment_date}}", "{{assessment_status}}", "{{assessment_scope_statement}}",
            "{{generated_table_of_contents}}", "{{environmental_evidence_register}}",
            "{{legal_and_knowledge_references}}", "{{project_and_gis_references}}"
    );

    public List<ValidationIssue> validate(GenerateReportRequest request, Set<String> templateTokens) {
        List<ValidationIssue> issues = new ArrayList<>();
        if (request == null) {
            return List.of(issue("REQUEST_REQUIRED", "A report request is required."));
        }
        require(request.projectName(), "projectName", issues);
        require(request.reportVersion(), "reportVersion", issues);
        require(request.studyArea(), "studyArea", issues);
        require(request.assessmentDate(), "assessmentDate", issues);
        if (clean(request.assessmentDate()) != null) {
            try {
                LocalDate.parse(request.assessmentDate().trim());
            } catch (DateTimeParseException exception) {
                issues.add(issue("INVALID_ASSESSMENT_DATE", "assessmentDate must use ISO format YYYY-MM-DD."));
            }
        }

        Map<String, EvidenceItem> evidenceById = new HashMap<>();
        for (int i = 0; i < request.evidence().size(); i++) {
            EvidenceItem evidence = request.evidence().get(i);
            if (evidence == null) {
                issues.add(issue("EVIDENCE_REQUIRED", "Evidence item at index " + i + " is null."));
                continue;
            }
            String id = clean(evidence.evidenceId());
            if (id == null || !STABLE_ID.matcher(id).matches()) {
                issues.add(new ValidationIssue("INVALID_EVIDENCE_ID",
                        "Evidence IDs must be stable identifiers containing 2–100 letters, numbers, dot, underscore, colon or hyphen.",
                        evidence.evidenceId(), null));
            } else if (evidenceById.putIfAbsent(id, evidence) != null) {
                issues.add(new ValidationIssue("DUPLICATE_EVIDENCE_ID",
                        "Evidence IDs must be unique in a report request.", id, null));
            }
            validateEvidence(evidence, issues);
        }

        if (request.claims().isEmpty()) {
            issues.add(issue("REPORT_CLAIMS_REQUIRED",
                    "At least one evidence-backed report claim is required; unsupported boilerplate is not generated."));
        }
        for (int i = 0; i < request.claims().size(); i++) {
            ReportClaim claim = request.claims().get(i);
            if (claim == null) {
                issues.add(issue("CLAIM_REQUIRED", "Report claim at index " + i + " is null."));
                continue;
            }
            String index = Integer.toString(i);
            requireClaimField(claim.sectionId(), "sectionId", index, issues);
            requireClaimField(claim.statement(), "statement", index, issues);
            String token = clean(claim.templateToken());
            if (token == null || !templateTokens.contains(token)) {
                issues.add(new ValidationIssue("UNKNOWN_TEMPLATE_TOKEN",
                        "Claim refers to a token that is not present in the configured DOCX template.", null, index));
            } else if (SYSTEM_TOKENS.contains(token)) {
                issues.add(new ValidationIssue("SYSTEM_TEMPLATE_TOKEN",
                        "This template token is generated by the report pipeline and cannot be supplied as a report claim.", null, index));
            }
            if (claim.evidenceIds().isEmpty()) {
                issues.add(new ValidationIssue("CLAIM_WITHOUT_EVIDENCE",
                        "Every factual report claim must cite one or more evidence IDs.", null, index));
            }
            List<EvidenceItem> citedEvidence = new ArrayList<>();
            for (String evidenceId : claim.evidenceIds()) {
                EvidenceItem evidence = evidenceById.get(evidenceId);
                if (evidence == null) {
                    issues.add(new ValidationIssue("UNKNOWN_EVIDENCE_ID",
                            "Claim cites an evidence ID that is missing from the evidence package.", evidenceId, index));
                } else {
                    citedEvidence.add(evidence);
                }
            }
            validateNumbers(claim, citedEvidence, index, issues);
        }
        for (int i = 0; i < request.tableRows().size(); i++) {
            ReportTableRow row = request.tableRows().get(i);
            String index = "tableRow-" + i;
            if (row == null) {
                issues.add(new ValidationIssue("TABLE_ROW_REQUIRED", "Table row at index " + i + " is null.", null, index));
                continue;
            }
            Map<String, Set<String>> allowedCells = Map.of(
                    "impact_matrix", Set.of("phase_component", "pathway_basis", "significance_uncertainty", "mitigation_consideration", "evidence_ids"),
                    "mitigation_plan", Set.of("impact_evidence_id", "action", "phase_location", "responsible_party", "timing_indicator_cost"),
                    "monitoring_plan", Set.of("parameter_receptor", "location_method", "frequency_phase", "standard_trigger", "responsibility_reporting"));
            Set<String> allowed = allowedCells.get(row.tableId());
            if (allowed == null) {
                issues.add(new ValidationIssue("UNKNOWN_TABLE_ID", "Table row refers to an unsupported repeatable table.", null, index));
            } else if (row.cells().isEmpty() || !allowed.containsAll(row.cells().keySet())) {
                issues.add(new ValidationIssue("INVALID_TABLE_ROW_CELLS", "Table row contains no cells or uses unsupported cell names.", null, index));
            }
            if (row.evidenceIds().isEmpty()) {
                issues.add(new ValidationIssue("TABLE_ROW_WITHOUT_EVIDENCE", "Every factual table row must cite one or more evidence IDs.", null, index));
            }
            List<EvidenceItem> citedEvidence = new ArrayList<>();
            for (String evidenceId : row.evidenceIds()) {
                EvidenceItem cited = evidenceById.get(evidenceId);
                if (cited == null) issues.add(new ValidationIssue("UNKNOWN_EVIDENCE_ID",
                        "Table row cites an evidence ID that is missing from the evidence package.", evidenceId, index));
                else citedEvidence.add(cited);
            }
            String text = String.join(" ", row.cells().values());
            ReportClaim numericProxy = new ReportClaim(row.tableId(), "", text, row.evidenceIds(), row.numericClaims());
            validateNumbers(numericProxy, citedEvidence, index, issues);
        }
        return List.copyOf(issues);
    }

    private static void validateEvidence(EvidenceItem item, List<ValidationIssue> issues) {
        EvidenceType type = item.type();
        if (type == null) {
            issues.add(new ValidationIssue("EVIDENCE_TYPE_REQUIRED", "Evidence type is required.", item.evidenceId(), null));
            return;
        }
        if (clean(item.claim()) == null) {
            issues.add(new ValidationIssue("EVIDENCE_CLAIM_REQUIRED", "Evidence must include the supported claim or observation.",
                    item.evidenceId(), null));
        }
        switch (type) {
            case PROJECT_DOCUMENT_CLAIM -> {
                requireEvidence(item.sourceTitle(), "sourceTitle", item.evidenceId(), issues);
                requireEvidence(item.sourceFileName(), "sourceFileName", item.evidenceId(), issues);
                requireEvidence(item.chunkId(), "chunkId", item.evidenceId(), issues);
                requireEvidence(item.excerpt(), "excerpt", item.evidenceId(), issues);
                if (item.pageNumber() == null || item.pageNumber() < 1) {
                    issues.add(new ValidationIssue("DOCUMENT_PAGE_REQUIRED",
                            "Project-document evidence must include a page number greater than zero.", item.evidenceId(), null));
                }
            }
            case USER_PROVIDED_PROJECT_INPUT -> {
                requireEvidence(item.sourceTitle(), "sourceTitle", item.evidenceId(), issues);
                requireEvidence(item.sourceLocator(), "sourceLocator", item.evidenceId(), issues);
                requireEvidence(item.excerpt(), "excerpt", item.evidenceId(), issues);
                if (item.limitations().isEmpty()) {
                    issues.add(new ValidationIssue("USER_INPUT_LIMITATIONS_REQUIRED",
                            "User-provided project inputs must be labeled unverified and state their limitations.", item.evidenceId(), null));
                }
            }
            case GIS_OBSERVATION -> {
                requireEvidence(item.gisLayer(), "gisLayer", item.evidenceId(), issues);
                requireEvidence(item.operation(), "operation", item.evidenceId(), issues);
                requireEvidence(item.metric(), "metric", item.evidenceId(), issues);
                requireEvidence(item.value(), "value", item.evidenceId(), issues);
                requireEvidence(item.units(), "units", item.evidenceId(), issues);
                if (item.limitations().isEmpty()) {
                    issues.add(new ValidationIssue("GIS_LIMITATIONS_REQUIRED",
                            "GIS observations must state their analysis limitations.", item.evidenceId(), null));
                }
            }
            case GUIDANCE_REFERENCE -> {
                requireEvidence(item.sourceTitle(), "sourceTitle", item.evidenceId(), issues);
                requireEvidence(item.sourceVersion(), "sourceVersion", item.evidenceId(), issues);
                requireEvidence(item.jurisdiction(), "jurisdiction", item.evidenceId(), issues);
                requireEvidence(item.applicability(), "applicability", item.evidenceId(), issues);
                requireEvidence(item.sourceLocator(), "sourceLocator", item.evidenceId(), issues);
                requireEvidence(item.excerpt(), "excerpt", item.evidenceId(), issues);
            }
            case MARG_INTERPRETATION -> {
                if (item.limitations().isEmpty()) {
                    issues.add(new ValidationIssue("INTERPRETATION_LIMITATIONS_REQUIRED",
                            "MARG interpretations must state limitations or uncertainty.", item.evidenceId(), null));
                }
            }
        }
    }

    private static void validateNumbers(
            ReportClaim claim,
            List<EvidenceItem> citedEvidence,
            String claimIndex,
            List<ValidationIssue> issues
    ) {
        Set<BigDecimal> declaredNumbers = new HashSet<>();
        for (NumericValue number : claim.numericClaims()) {
            if (number == null || number.value() == null || clean(number.units()) == null) {
                issues.add(new ValidationIssue("INVALID_NUMERIC_CLAIM",
                        "Each declared numeric claim must include a numeric value and units.", null, claimIndex));
                continue;
            }
            declaredNumbers.add(normalize(number.value()));
            boolean supported = citedEvidence.stream().anyMatch(e -> supports(e, number));
            if (!supported) {
                issues.add(new ValidationIssue("UNSUPPORTED_NUMERIC_CLAIM",
                        "Numeric value " + number.value().stripTrailingZeros().toPlainString() + " " + number.units()
                                + " is not supported by the cited evidence with matching units.", null, claimIndex));
            }
        }
        Matcher matcher = NUMBERS.matcher(claim.statement() == null ? "" : claim.statement());
        while (matcher.find()) {
            BigDecimal number = parseNumber(matcher.group());
            if (number != null && !declaredNumbers.contains(normalize(number))) {
                issues.add(new ValidationIssue("UNDECLARED_NUMERIC_CLAIM",
                        "Every number in report text must be declared with units and linked to evidence.", null, claimIndex));
                break;
            }
        }
    }

    private static boolean supports(EvidenceItem evidence, NumericValue claimNumber) {
        for (NumericValue sourceNumber : evidence.numericValues()) {
            if (sourceNumber != null && sourceNumber.value() != null
                    && normalize(sourceNumber.value()).compareTo(normalize(claimNumber.value())) == 0
                    && equalText(sourceNumber.units(), claimNumber.units())) {
                return true;
            }
        }
        if (evidence.type() == EvidenceType.GIS_OBSERVATION && evidence.value() != null) {
            BigDecimal value = parseNumber(evidence.value());
            return value != null && normalize(value).compareTo(normalize(claimNumber.value())) == 0
                    && equalText(evidence.units(), claimNumber.units());
        }
        return false;
    }

    private static BigDecimal parseNumber(String value) {
        try {
            return new BigDecimal(value.replace(",", ""));
        } catch (NumberFormatException ex) {
            return null;
        }
    }

    private static BigDecimal normalize(BigDecimal value) {
        return value.stripTrailingZeros();
    }

    private static void require(String value, String field, List<ValidationIssue> issues) {
        if (clean(value) == null) {
            issues.add(issue("REQUIRED_FIELD_MISSING", "Required report field is missing: " + field + "."));
        }
    }

    private static void requireEvidence(String value, String field, String id, List<ValidationIssue> issues) {
        if (clean(value) == null) {
            issues.add(new ValidationIssue("EVIDENCE_PROVENANCE_MISSING",
                    "Evidence field is required: " + field + ".", id, null));
        }
    }

    private static void requireClaimField(String value, String field, String index, List<ValidationIssue> issues) {
        if (clean(value) == null) {
            issues.add(new ValidationIssue("CLAIM_FIELD_MISSING", "Claim field is required: " + field + ".", null, index));
        }
    }

    private static ValidationIssue issue(String code, String message) {
        return new ValidationIssue(code, message, null, null);
    }

    private static String clean(String value) {
        return value == null || value.isBlank() ? null : value.trim();
    }

    private static boolean equalText(String left, String right) {
        return left != null && right != null && left.trim().equalsIgnoreCase(right.trim());
    }
}
